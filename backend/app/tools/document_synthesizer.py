"""
Document Synthesis Tool
Compiles research literature, analysis, and briefs into structured, formatted documents.
Calculates bit-level SHA-256 checksums and prepares files for verified upload.
"""
import hashlib
import os
import re
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field
from backend.app.schemas.common import RiskTier
from backend.app.tools.base import BaseTool, ExecutionContext


class SynthesizerInput(BaseModel):
    title: str = Field(min_length=3, description="Document title")
    content: str = Field(description="Body content or synthesis text")
    format: str = Field(default="markdown", description="'markdown' or 'text'")
    sections: Optional[List[str]] = Field(default=None, description="Optional custom section headers")
    citations: Optional[List[Dict[str, Any]]] = Field(default=None, description="List of paper citations or source metadata")


class SynthesizedDocumentResult(BaseModel):
    file_name: str
    title: str
    content: str
    format: str
    size_bytes: int
    section_count: int
    sha256_checksum: str
    local_sandbox_path: Optional[str] = None


class DocumentSynthesizerTool(BaseTool):
    name = "document_synthesizer"
    description = "Compiles structured research briefs, executive summaries, and comparative reports in the sandbox."
    category = "content"
    base_risk_tier = RiskTier.TIER_1_REVERSIBLE
    required_scopes = ["sandbox.write"]
    requires_approval = False
    input_schema = SynthesizerInput
    output_schema = SynthesizedDocumentResult
    verification_contract = {
        "verifier": "DocumentIntegrityVerifier",
        "assertions": [
            "size_greater_than_zero",
            "sha256_checksum_valid",
            "markdown_headings_present"
        ]
    }

    async def execute(self, params: SynthesizerInput, context: ExecutionContext) -> SynthesizedDocumentResult:
        """
        Structures the document, appends formatted metadata & citations, and writes to sandbox.
        """
        timestamp_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

        # Normalize filename
        clean_title = re.sub(r"[^\w\-_]", "_", params.title).strip("_").lower()
        file_name = f"{clean_title}.md" if params.format == "markdown" else f"{clean_title}.txt"

        # Build formatted document body
        doc_lines = [
            f"# {params.title}",
            f"*Generated by Aegis Autonomous Execution Runtime on {timestamp_str}*",
            "",
            "---",
            "",
            "## 1. Executive Summary",
            params.content,
            ""
        ]

        # Add citations if present
        if params.citations:
            doc_lines.extend([
                "## 2. Peer-Reviewed Citations & Methodology References",
                "| arXiv ID | Title | Authors | Year |",
                "| :--- | :--- | :--- | :--- |"
            ])
            for cite in params.citations:
                c_id = cite.get("arxiv_id", "N/A")
                c_title = cite.get("title", "Untitled")
                c_authors = ", ".join(cite.get("authors", []))[:40]
                c_year = cite.get("published", "")[:4] or "2024"
                doc_lines.append(f"| [{c_id}](https://arxiv.org/abs/{c_id}) | {c_title} | {c_authors} | {c_year} |")
            doc_lines.append("")

        final_content = "\n".join(doc_lines)
        content_bytes = final_content.encode("utf-8")
        size_bytes = len(content_bytes)
        sha256_hash = hashlib.sha256(content_bytes).hexdigest()

        # Count markdown section headers
        section_count = len(re.findall(r"^#{1,3}\s+", final_content, re.MULTILINE))

        local_path = None
        if context.sandbox_dir and os.path.exists(context.sandbox_dir):
            file_path = os.path.join(context.sandbox_dir, file_name)
            with open(file_path, "w", encoding="utf-8") as f:
                f.write(final_content)
            local_path = file_path

        return SynthesizedDocumentResult(
            file_name=file_name,
            title=params.title,
            content=final_content,
            format=params.format,
            size_bytes=size_bytes,
            section_count=max(section_count, 1),
            sha256_checksum=sha256_hash,
            local_sandbox_path=local_path
        )


document_synthesizer_tool = DocumentSynthesizerTool()
