"""
Aegis Core Enums and Shared Schema Types
"""
from enum import Enum


class RiskTier(str, Enum):
    TIER_0_READ = "TIER_0_READ"               # Pure read-only / ephemeral computation
    TIER_1_REVERSIBLE = "TIER_1_REVERSIBLE"   # Additive / sandboxed workspace write
    TIER_2_MUTATING = "TIER_2_MUTATING"       # External mutation / shared data modification
    TIER_3_DESTRUCTIVE = "TIER_3_DESTRUCTIVE" # Permanent deletion / permission revocation


class StepStatus(str, Enum):
    PENDING = "PENDING"
    PROPOSED = "PROPOSED"
    AWAITING_APPROVAL = "AWAITING_APPROVAL"
    APPROVED = "APPROVED"
    EXECUTING = "EXECUTING"
    VERIFYING = "VERIFYING"
    VERIFIED = "VERIFIED"
    FAILED = "FAILED"
    REJECTED = "REJECTED"
    RECOVERING = "RECOVERING"


class PlanStatus(str, Enum):
    PLANNING = "PLANNING"
    RUNNING = "RUNNING"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"
    HALTED = "HALTED"


class EventType(str, Enum):
    PLAN_GENERATION_STARTED = "PLAN_GENERATION_STARTED"
    PLAN_SYNTHESIZED = "PLAN_SYNTHESIZED"
    RISK_EVALUATED = "RISK_EVALUATED"
    APPROVAL_REQUESTED = "APPROVAL_REQUESTED"
    APPROVAL_GRANTED = "APPROVAL_GRANTED"
    APPROVAL_REJECTED = "APPROVAL_REJECTED"
    TOOL_EXECUTION_STARTED = "TOOL_EXECUTION_STARTED"
    TOOL_EXECUTION_COMPLETED = "TOOL_EXECUTION_COMPLETED"
    VERIFICATION_STARTED = "VERIFICATION_STARTED"
    VERIFICATION_PASSED = "VERIFICATION_PASSED"
    VERIFICATION_FAILED = "VERIFICATION_FAILED"
    RECOVERY_ATTEMPTED = "RECOVERY_ATTEMPTED"
    PLAN_COMPLETED = "PLAN_COMPLETED"
    PLAN_FAILED = "PLAN_FAILED"


class Severity(str, Enum):
    INFO = "INFO"
    WARNING = "WARNING"
    CRITICAL = "CRITICAL"


class Actor(str, Enum):
    SYSTEM = "SYSTEM"
    USER = "USER"
    VERIFIER = "VERIFIER"
    PLANNER = "PLANNER"
